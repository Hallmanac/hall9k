using System.Text;
using Hall9k.Connectors.Prompts;
using Hall9k.Connectors.Text;
using Hall9k.Domain.Features.Tasks.Events;
using Hall9k.Domain.Features.Tasks.Notes;
using Hall9k.Domain.Infrastructure.Ids;

namespace Hall9k.Daemon.ProjectHomes;

/// <summary>
/// <c>notes.md</c> beside a task's <c>task.md</c> in the project home: a projection of the task's own
/// notes, rewritten from the events by the render sweep for any task that holds some. It lives in the
/// project home and never in a worktree: review sessions run in the worktree, and a file there could
/// reach a reviewer. No prompt and no shipped skill names it; the prompt is the only way notes enter a
/// session.
/// <para>
/// Unlike <c>lessons.md</c> it is node-local on purpose, because the reader is a person on this node
/// and the one thing worth showing beside a note is whether this node would put it in a prompt. A held
/// note is marked held rather than left out, so a person sees the whole record.
/// </para>
/// </summary>
public static class TaskNotesDocument
{
    /// <summary>The file's name beside <c>task.md</c>.</summary>
    public const string FileName = "notes.md";

    /// <summary>
    /// The sentence marking this file as the platform's own render, checked before anything is
    /// overwritten: a file of the same name that lacks it is somebody's own and is left alone.
    /// </summary>
    public const string GeneratedMarker = "Generated by `h9k` from the task's notes";

    /// <summary>The document for <paramref name="views"/>, which are this task's own notes already marked and ordered newest first.</summary>
    public static string Render(Guid taskId, IReadOnlyList<TaskNoteView> views, Func<TaskNoteEntry, string> author)
    {
        string shortId = DomainId.Short(taskId);
        StringBuilder document = new();
        document.AppendLine($"# Notes on task {shortId}");
        document.AppendLine();
        document.AppendLine(
            $"> {GeneratedMarker}: a projection of the events on the task's stream, rewritten whenever they "
            + "change, so an edit here does not survive. Leave a note with "
            + $"`h9k task note {shortId} \"<text>\"`; a person reads them at a terminal with "
            + $"`h9k task notes {shortId}`.");
        document.AppendLine();
        document.AppendLine(
            $"{views.Count} note{(views.Count == 1 ? string.Empty : "s")}, newest first. A note marked HELD is kept "
            + "out of every session's prompt by the trust rule lessons use, and is shown here so a person can "
            + "judge it. Each note's outcome says what the closeout promotion step made of it: kept as a lesson, "
            + "dropped with its reason, held, or undecided when no step decided it.");

        foreach (TaskNoteView view in views)
        {
            TaskNoteRecorded note = view.Entry.Note;
            string session = note.SessionName.IsNotBlank()
                ? RelayedText.OneLine(note.SessionName)
                : note.SessionId.IsNotBlank() ? RelayedText.OneLine(note.SessionId) : "no session";
            document.AppendLine();
            document.AppendLine(
                $"## {note.RecordedAt.ToUniversalTime():yyyy-MM-dd HH:mm:ss}Z{(view.ReachesAPrompt ? string.Empty : " (HELD)")}");
            document.AppendLine();
            document.AppendLine(RelayedText.Printable(note.Text));
            document.AppendLine();
            document.AppendLine(
                $"- id: {note.NoteId}\n- author: {RelayedText.OneLine(author(view.Entry))}\n- session: {session}\n"
                + $"- source: {note.Source.Label}\n- provenance: {view.Mark.Label}\n- outcome: {view.OutcomeLabel}");
        }

        return document.ToString();
    }

    /// <summary>
    /// The author of a replicated note the way a replicated handoff note names its sender
    /// (<see cref="ReplicatedNote.Origin"/>), because the recorded owner id resolves to nobody on
    /// another node; a note this node recorded names its owner.
    /// </summary>
    public static string Author(TaskNoteEntry entry, LocalFleet? localFleet) =>
        entry.ReceivedFromNodeId is { } sender
            ? ReplicatedNote.Origin(sender, entry.OriginNodeId, localFleet)
            : entry.Note.Provenance is { } provenance
                ? $"owner {DomainId.Short(provenance.RecordedByOwnerId)}"
                : "unknown author";
}
