using System.Text;
using Hall9k.Domain.Features.Project.Handlers;
using Hall9k.Domain.Features.Project.Projections;
using Hall9k.Domain.Infrastructure.Storage;

namespace Hall9k.Domain.Features.Project.Rendering;

/// <summary>What <see cref="SolutionAgentsDocument.Write"/> did with the file at the home's <c>AGENTS.md</c> path.</summary>
public enum SolutionAgentsWriteOutcome
{
    /// <summary>No file was there; the render is now.</summary>
    Created,

    /// <summary>A render of this solution was there and differed; it was replaced.</summary>
    Rewritten,

    /// <summary>The file already holds exactly these bytes; nothing was written.</summary>
    Unchanged,

    /// <summary>A file this platform did not render for this solution sits there, and was left alone.</summary>
    Refused,
}

/// <summary>
/// The <c>AGENTS.md</c> in a solution's thin home: a render of the solution's membership and of
/// where this node holds each member, never a hand-maintained file. It sits in the domain beside
/// the task and idea renderers because the CLI writes the first copy at <c>h9k solution init</c>
/// and the daemon's home render sweep rewrites it whenever the membership, a member's home or the
/// solution's name changes, and both must produce the same bytes.
/// <para>
/// Every fact in it is read off the <see cref="SolutionMembership"/> and the registered projects,
/// so a membership that arrives by replication and a member this node joins later both change the
/// bytes on the next sweep. It names the solution's key as well as its name: the path is derived
/// from the name at first, but the key is what <see cref="SolutionHomePaths.For"/> finds a home by
/// afterwards, so a renamed solution keeps its home and a different solution whose name slugs the
/// same is told apart.
/// </para>
/// </summary>
public static class SolutionAgentsDocument
{
    /// <summary>
    /// The line every render carries, and the only signal this has for telling its own past output
    /// apart from a file that merely happens to sit at the same path.
    /// </summary>
    public const string GeneratedMarker = "Generated by `h9k` from this solution's membership";

    private const string KeyLinePrefix = "Solution key: `";

    /// <summary>The statement for a member this node has registered and joined no copy of.</summary>
    public const string NotJoinedStatement = "This node has not joined this project.";

    /// <summary>
    /// Whether <paramref name="current"/> is this platform's own render for the solution with
    /// <paramref name="key"/>: it carries the marker and names that key.
    /// </summary>
    public static bool IsRenderFor(string current, string key) =>
        current.Contains(GeneratedMarker, StringComparison.Ordinal)
        && current.Contains($"{KeyLinePrefix}{key}`", StringComparison.OrdinalIgnoreCase);

    /// <summary>
    /// The solution key the platform's own render in <paramref name="home"/> names, or null when
    /// there is no readable <c>AGENTS.md</c> there or it is not a render (no marker, no key line).
    /// This is how a home is tied to its solution without trusting the directory name, which is a
    /// lossy slug that a rename changes and two different names can share.
    /// </summary>
    public static string? RenderedKeyIn(string home)
    {
        string path = ProjectHomePaths.AgentsFile(home);
        try
        {
            if (!File.Exists(path))
            {
                return null;
            }

            string content = File.ReadAllText(path);
            if (!content.Contains(GeneratedMarker, StringComparison.Ordinal))
            {
                return null;
            }

            int start = content.IndexOf(KeyLinePrefix, StringComparison.Ordinal);
            if (start < 0)
            {
                return null;
            }

            start += KeyLinePrefix.Length;
            int end = content.IndexOf('`', start);
            return end > start
                ? content[start..end]
                : null;
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
        {
            return null;
        }
    }

    /// <summary>
    /// Whether an <c>AGENTS.md</c> the platform did not render for the solution with
    /// <paramref name="key"/> already sits in <paramref name="home"/>, checked before a recipe writes
    /// anything else so the refusal costs nothing. False when there is no file.
    /// </summary>
    public static bool IsForeign(string home, string key)
    {
        string path = ProjectHomePaths.AgentsFile(home);
        return File.Exists(path) && !IsRenderFor(File.ReadAllText(path), key);
    }

    /// <summary>
    /// Writes <paramref name="rendered"/> as the home's <c>AGENTS.md</c>, touching disk only when the
    /// bytes differ and never over a file this platform did not render for <paramref name="key"/>.
    /// </summary>
    public static SolutionAgentsWriteOutcome Write(string home, string key, string rendered)
    {
        string path = ProjectHomePaths.AgentsFile(home);
        bool existed = File.Exists(path);
        if (existed)
        {
            string current = File.ReadAllText(path);
            if (current == rendered)
            {
                return SolutionAgentsWriteOutcome.Unchanged;
            }

            if (!IsRenderFor(current, key))
            {
                return SolutionAgentsWriteOutcome.Refused;
            }
        }

        File.WriteAllText(path, rendered);
        return existed
            ? SolutionAgentsWriteOutcome.Rewritten
            : SolutionAgentsWriteOutcome.Created;
    }

    public static string Render(
        SolutionMembership membership, IReadOnlyList<ProjectDetails> projects, Func<Guid, string?> rootFingerprintOf)
    {
        StringBuilder document = new();
        string name = membership.Name;

        document.AppendLine($"# {name}: solution home");
        document.AppendLine();
        document.AppendLine(
            $"> {GeneratedMarker}. Do not edit it: the daemon's home render sweep and `h9k solution init` "
            + "overwrite it. Change the membership (`h9k solution link`, `unlink`, `rename`) and the file follows; "
            + "the home keeps its directory when the solution is renamed.");
        document.AppendLine();
        document.AppendLine($"{KeyLinePrefix}{membership.Key}`");
        document.AppendLine();
        document.AppendLine(membership.State == SolutionState.Closed
            ? $"State: closed ({membership.CloseReason}). A closed solution is final; this home stays on disk."
            : "State: open.");
        document.AppendLine();
        document.AppendLine(
            "This is the thin home of one interactive solution window. The window directs the member "
            + "projects' own orchestrators: it reads the solution board, walks member projects' ideas, cuts "
            + "tasks into any member with `--project`, and sends each act that belongs to a member to that "
            + "member's live orchestrator. It registers no orchestrator presence of its own and never drains "
            + "a member's feed. Ideas stay in the member projects; there is no `repo/`, `ideas/` or `tasks/` here.");
        document.AppendLine();
        document.AppendLine("## Members");
        document.AppendLine();

        foreach (SolutionMember member in membership.Members)
        {
            ProjectDetails? held = SolutionDecider.HeldProject(member, projects, rootFingerprintOf);
            document.AppendLine($"### {member.Name}");
            document.AppendLine();
            document.AppendLine($"- Repository: {member.RepositoryUrl}");
            document.AppendLine(held switch
            {
                null => $"- Home on this node: {NotJoinedStatement}",
                { HomeDirectory.HasValue: true } => $"- Home on this node: {held.HomeDirectory.Value}",
                _ => "- Home on this node: joined here, but this node has no home recorded for it (`h9k project init`).",
            });
            document.AppendLine();
        }

        document.AppendLine("## Working from here");
        document.AppendLine();
        document.AppendLine($"- The board: `h9k solution show \"{name}\"`.");
        document.AppendLine("- A member's orchestrator presence: `h9k orchestrator status --project <member>`.");
        document.AppendLine("- A member's launch line, for a terminal where none is live: `h9k orchestrator project <member>`.");
        document.AppendLine("- Ideas of a member: `h9k idea list --project <member>`. A task into a member: `h9k task add --project <member> …`.");
        document.AppendLine("- The recipe this window follows is `recipes/orchestrator.md`, written by the `orchestrator-recipe-generator` skill.");

        return document.ToString().ReplaceLineEndings("\n");
    }
}
